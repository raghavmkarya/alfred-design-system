/* Alfred AI — Inspiration Library.
   Browsable catalog of marketing section patterns rebuilt on the design
   system: live iframe previews (light / marketing dark), variant tabs,
   viewport widths, copy-HTML and standalone download. Schema comes from
   library/sections.json, generated by scripts/gen-library.mjs and gated by
   scripts/verify-library.mjs. Authored in plain React.createElement so there
   is no build step, exactly like the playground. */
(function () {
  "use strict";
  var h = React.createElement;

  var THEMES = [
    { id: "light", label: "Light" },
    { id: "dark", label: "Marketing dark" },
  ];
  var VIEWPORTS = [
    { id: "390", label: "Mobile", width: 390 },
    { id: "768", label: "Tablet", width: 768 },
    { id: "1120", label: "Content", width: 1120 },
    { id: "1440", label: "Full", width: 1440 },
  ];
  var TIERS = [
    { id: "all", label: "All tiers" },
    { id: "1", label: "Tier 1" },
    { id: "2", label: "Tier 2" },
    { id: "3", label: "Tier 3" },
  ];
  var THUMB_H = 230;
  var THUMB_W = 1120;

  function previewUrl(sectionId, variantId, theme) {
    return "preview.html?section=" + encodeURIComponent(sectionId)
      + (variantId ? "&variant=" + encodeURIComponent(variantId) : "")
      + (theme === "dark" ? "&theme=dark" : "");
  }

  function parseHash() {
    var m = location.hash.match(/^#\/s\/([^/]+)$/);
    if (m) return { view: "detail", id: decodeURIComponent(m[1]) };
    m = location.hash.match(/^#\/c\/([^/]+)$/);
    if (m) return { view: "browse", category: decodeURIComponent(m[1]) };
    return { view: "browse", category: "all" };
  }

  /* Resolve styles.css (import-only) into one flat stylesheet for standalone
     downloads. Fonts stay repo-relative and will fall back off-repo; the
     export is a visual reference, not a deployable page. */
  var cssPromise = null;
  function flatCss() {
    if (cssPromise) return cssPromise;
    cssPromise = fetch("../styles.css")
      .then(function (r) { return r.text(); })
      .then(function (root) {
        var imports = [];
        root.replace(/@import\s+(?:url\()?["']?([^"')]+)["']?\)?\s*;/g, function (_, p) { imports.push(p); return _; });
        return Promise.all(imports.map(function (p) {
          return fetch("../" + p).then(function (r) { return r.text(); });
        })).then(function (parts) { return parts.join("\n"); });
      });
    return cssPromise;
  }

  function download(name, text) {
    var a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([text], { type: "text/html" }));
    a.download = name;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  function seg(label, items, value, set) {
    return h("div", { role: "group", "aria-label": label, className: "lib-seg" },
      items.map(function (it) {
        return h("button", {
          key: it.id, type: "button", "aria-pressed": it.id === value ? "true" : "false",
          onClick: function () { set(it.id); },
        }, it.label);
      }));
  }

  /* —— browse card: a scaled live preview ————————————————————— */
  function Thumb(props) {
    var ref = React.useRef(null);
    var ws = React.useState(360), w = ws[0], setW = ws[1];
    React.useEffect(function () {
      function measure() { if (ref.current) setW(ref.current.clientWidth || 360); }
      measure();
      window.addEventListener("resize", measure);
      return function () { window.removeEventListener("resize", measure); };
    }, []);
    var scale = w / THUMB_W;
    return h("div", { className: "lib-thumb", ref: ref },
      h("iframe", {
        src: previewUrl(props.section.id, null, props.theme),
        title: props.section.name + " preview",
        loading: "lazy", tabIndex: -1, "aria-hidden": "true",
        style: { height: (THUMB_H / scale) + "px", transform: "scale(" + scale + ")" },
      }));
  }

  function Card(props) {
    var s = props.section;
    return h("button", { className: "lib-card", type: "button", onClick: function () { location.hash = "#/s/" + s.id; } },
      h(Thumb, { section: s, theme: props.theme }),
      h("div", { className: "lib-card-meta" },
        h("div", { className: "name" }, s.name),
        h("div", { className: "row" },
          h("span", { className: "lib-chip" + (s.tier === 1 ? " tier1" : "") }, "Tier " + s.tier),
          h("span", { className: "lib-chip" }, props.categoryName),
          (s.pageTypes || []).slice(0, 3).map(function (p) { return h("span", { key: p, className: "lib-chip" }, p); }))));
  }

  /* —— detail ————————————————————————————————————————————————— */
  function Detail(props) {
    var s = props.section;
    var vs = React.useState((s.variants && s.variants[0] && s.variants[0].id) || null),
        variant = vs[0], setVariant = vs[1];
    var vp = React.useState("1120"), viewport = vp[0], setViewport = vp[1];
    var hs = React.useState(420), frameH = hs[0], setFrameH = hs[1];
    var cp = React.useState(""), note = cp[0], setNote = cp[1];
    var frameRef = React.useRef(null);
    var src = previewUrl(s.id, variant, props.theme);

    React.useEffect(function () {
      function onMsg(ev) {
        if (ev.origin !== location.origin) return;
        var d = ev.data;
        if (!d || d.type !== "alfred-lib:height" || d.section !== s.id) return;
        if (frameRef.current && ev.source === frameRef.current.contentWindow) setFrameH(Math.max(220, d.height));
      }
      window.addEventListener("message", onMsg);
      return function () { window.removeEventListener("message", onMsg); };
    }, [s.id]);

    function markup() {
      try {
        var doc = frameRef.current && frameRef.current.contentDocument;
        var root = doc && doc.getElementById("root");
        return root ? root.innerHTML : null;
      } catch (e) { return null; }
    }
    function flash(msg) { setNote(msg); setTimeout(function () { setNote(""); }, 1800); }
    function copyHtml() {
      var m = markup();
      if (!m) return flash("Preview not ready");
      navigator.clipboard.writeText(m).then(function () { flash("Copied section HTML"); });
    }
    function downloadStandalone() {
      var m = markup();
      if (!m) return flash("Preview not ready");
      flatCss().then(function (css) {
        var docHtml = "<!-- Alfred Inspiration Library standalone export: " + s.id
          + (variant ? " / " + variant : "") + " / " + props.theme + " theme.\n"
          + "     Fonts are @font-face'd against repo-relative paths and fall back elsewhere. -->\n"
          + "<!doctype html>\n<html lang=\"en\"" + (props.theme === "dark" ? " data-theme=\"dark\"" : "") + ">\n<head>\n"
          + "<meta charset=\"utf-8\" />\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\" />\n"
          + "<title>Alfred — " + s.name + "</title>\n<style>\n" + css + "\nhtml, body { margin: 0; } body { background: var(--bg-page); }\n</style>\n"
          + "</head>\n<body>\n" + m + "\n</body>\n</html>\n";
        download("alfred-" + s.id + (variant ? "-" + variant : "") + ".html", docHtml);
      });
    }

    var width = VIEWPORTS.filter(function (v) { return v.id === viewport; })[0].width;
    return h("div", null,
      h("div", { style: { marginBlockEnd: 14, display: "flex", gap: 14, alignItems: "center", flexWrap: "wrap" } },
        h("button", { className: "lib-back", type: "button", onClick: function () { history.back(); } }, "← Library"),
        s.variants && s.variants.length > 1
          ? seg("Variant", s.variants.map(function (v) { return { id: v.id, label: v.name || v.id }; }), variant, setVariant)
          : null,
        seg("Viewport", VIEWPORTS, viewport, setViewport),
        note ? h("span", { style: { fontSize: "var(--text-xs)", color: "var(--text-link)" } }, note) : null),
      h("div", { className: "lib-detail" },
        h("div", { className: "lib-frame-wrap" },
          h("iframe", {
            key: src, ref: frameRef, src: src, title: s.name,
            style: { width: width + "px", height: frameH + "px" },
          })),
        h("aside", { className: "lib-panel" },
          h("h2", null, "About this pattern"),
          h("p", null, s.description),
          h("div", { className: "lib-actions" },
            h("button", { className: "lib-btn", type: "button", onClick: copyHtml }, "Copy HTML"),
            h("button", { className: "lib-btn", type: "button", onClick: downloadStandalone }, "Download standalone"),
            h("a", { className: "lib-btn", style: { textDecoration: "none" }, href: "export/" + s.id + ".html", target: "_blank", rel: "noopener" }, "Static export")),
          h("h2", { style: { marginBlockStart: 18 } }, "Facts"),
          h("div", { className: "lib-kv" }, h("span", null, "Tier"), h("code", null, String(s.tier))),
          h("div", { className: "lib-kv" }, h("span", null, "Pages"), h("code", null, (s.pageTypes || []).join(", "))),
          h("div", { className: "lib-kv" }, h("span", null, "Global"), h("code", null, "window." + s.global)),
          h("div", { className: "lib-kv" }, h("span", null, "Source"), h("code", null, s.file.replace(/\.js$/, ".jsx"))),
          s.props && s.props.length ? h("div", null,
            h("h2", { style: { marginBlockStart: 18 } }, "Props"),
            s.props.map(function (p) {
              return h("div", { className: "lib-kv", key: p.name }, h("span", null, p.name), h("code", null, p.type));
            })) : null,
          s.usedBy && s.usedBy.length ? h("div", null,
            h("h2", { style: { marginBlockStart: 18 } }, "Seen in the wild"),
            h("div", { className: "lib-actions", style: { marginBlockStart: 0 } },
              s.usedBy.map(function (u) {
                return h("a", {
                  key: u.site, className: "lib-chip", href: u.url || ("https://" + u.site),
                  target: "_blank", rel: "noopener", title: u.note || "", style: { textDecoration: "none" },
                }, u.site);
              }))) : null)));
  }

  /* —— app ————————————————————————————————————————————————————— */
  function App(props) {
    var data = props.data;
    var rt = React.useState(parseHash()), route = rt[0], setRoute = rt[1];
    var th = React.useState(localStorage.getItem("alfred-lib-theme") === "light" ? "light" : "dark"),
        theme = th[0], setThemeRaw = th[1];
    var tf = React.useState("all"), tier = tf[0], setTier = tf[1];
    var q = React.useState(""), query = q[0], setQuery = q[1];
    function setTheme(t) { localStorage.setItem("alfred-lib-theme", t); setThemeRaw(t); }

    React.useEffect(function () {
      function onHash() { setRoute(parseHash()); }
      window.addEventListener("hashchange", onHash);
      return function () { window.removeEventListener("hashchange", onHash); };
    }, []);

    var byId = {};
    data.sections.forEach(function (s) { byId[s.id] = s; });
    var catName = {};
    data.categories.forEach(function (c) { catName[c.id] = c.name; });

    var rail = h("aside", { className: "lib-rail" },
      h("div", { className: "lib-brand" },
        h("img", { src: "../assets/logos/alfred-logo-primary.svg", alt: "Alfred" }),
        h("span", null, "Inspiration Library")),
      h("input", {
        type: "text", className: "lib-search", value: query,
        placeholder: "Search " + data.sections.length + " patterns",
        "aria-label": "Search patterns",
        onChange: function (e) { setQuery(e.target.value); },
      }),
      h("div", { className: "lib-group" }, "Categories"),
      [{ id: "all", name: "All patterns", count: data.sections.length }]
        .concat(data.categories).map(function (c) {
          var current = route.view === "browse" && (route.category || "all") === c.id;
          return h("button", {
            key: c.id, className: "lib-item", type: "button",
            "aria-current": current ? "true" : undefined,
            onClick: function () { location.hash = c.id === "all" ? "#/" : "#/c/" + c.id; },
          }, h("span", null, c.name), h("span", { className: "count" }, String(c.count)));
        }),
      data.recipes && data.recipes.length ? h("div", null,
        h("div", { className: "lib-group" }, "Recipe pages"),
        data.recipes.map(function (r) {
          return h("a", {
            key: r.slug, className: "lib-item", style: { textDecoration: "none" },
            href: "recipes/" + r.slug + ".html", target: "_blank", rel: "noopener",
            title: r.subtitle || "",
          }, h("span", null, r.name || r.slug), h("span", { className: "count" }, "page"));
        })) : null,
      data.styles && data.styles.length ? h("div", null,
        h("div", { className: "lib-group" }, "Style lab"),
        h("a", {
          className: "lib-item", style: { textDecoration: "none" },
          href: "styles/index.html", target: "_blank", rel: "noopener",
        }, h("span", null, "All eight directions"), h("span", { className: "count" }, "lab")),
        data.styles.map(function (s) {
          return h("a", {
            key: s.slug, className: "lib-item", style: { textDecoration: "none" },
            href: "styles/" + s.slug + ".html", target: "_blank", rel: "noopener",
          }, h("span", null, s.name || s.slug), h("span", { className: "count" }, "style"));
        })) : null);

    var body;
    if (route.view === "detail" && byId[route.id]) {
      var s = byId[route.id];
      body = h("main", { className: "lib-main" },
        h("div", { className: "lib-bar" },
          h("div", null, h("h1", null, s.name)),
          h("div", { className: "sub" }, catName[s.category] || s.category),
          seg("Theme", THEMES, theme, setTheme)),
        h("div", { className: "lib-stage" }, h(Detail, { key: s.id, section: s, theme: theme })));
    } else {
      var list = data.sections.filter(function (s) {
        if (route.view === "browse" && route.category && route.category !== "all" && s.category !== route.category) return false;
        if (tier !== "all" && String(s.tier) !== tier) return false;
        if (query) {
          var hay = (s.name + " " + s.id + " " + s.description + " " + (s.pageTypes || []).join(" ")).toLowerCase();
          if (hay.indexOf(query.toLowerCase()) === -1) return false;
        }
        return true;
      });
      body = h("main", { className: "lib-main" },
        h("div", { className: "lib-bar" },
          h("div", null, h("h1", null, route.category && route.category !== "all" ? catName[route.category] : "All patterns")),
          h("div", { className: "sub" }, String(list.length) + " pattern" + (list.length === 1 ? "" : "s")),
          seg("Tier", TIERS, tier, setTier),
          seg("Theme", THEMES, theme, setTheme)),
        h("div", { className: "lib-stage" },
          list.length
            ? h("div", { className: "lib-grid" }, list.map(function (s) {
                return h(Card, { key: s.id + ":" + theme, section: s, theme: theme, categoryName: catName[s.category] || s.category });
              }))
            : h("div", { className: "lib-empty" }, "No pattern matches. Clear the search or the tier filter.")));
    }

    return h("div", { className: "lib" }, rail, body);
  }

  fetch("sections.json")
    .then(function (r) { if (!r.ok) throw new Error("sections.json " + r.status); return r.json(); })
    .then(function (data) {
      ReactDOM.createRoot(document.getElementById("root")).render(h(App, { data: data }));
      document.body.dataset.ready = "1";
    })
    .catch(function (err) {
      document.getElementById("root").innerHTML =
        '<p style="font-family:var(--font-sans);padding:40px">Could not load the library schema: '
        + String(err.message) + ". Run <code>node scripts/gen-library.mjs</code>.</p>";
    });
})();
